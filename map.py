"""目标地图：以 ①②③ 号位方向为 0°，记录各目标的水平相对角度。

为什么用相对角度：
    云台水平方向由直流电机 B 控制，没有位置记忆，记不住"绝对朝向"；
    但 ①②③ 号位在地图上聚成一竖排，方向几乎相同且贴有 AprilTag、
    容易先找到——把它们的方向定为 0°，其余目标都记录
    "相对 0° 转过多少度"。只要先找到任意一个基准标签完成"对零"，
    之后就能按角度推算其他目标该往哪转、转多少。

角度约定：
    0°     —— 从机器人指向 ①②③ 号位的方向
    正方向 —— 从 0° 往 ④⑤⑥ 一侧转（在地图图面上看是顺时针）
    范围   —— 0～360 度
    实际转向与电机正负号的关系由 VOLTAGE_POLARITY 决定，
    若发现"地图说往 ④⑤⑥ 转、机器人却往 ⑨⑩ 转"，把本表角度取负即可。

注意：下表角度按 120×60 厘米场地地图估算，误差约 ±10 度，
跑几次后用 record_angle() 记录实测值替换。
"""

# 0° 基准：①②③ 号位聚在同一方向，找到其中任意一个即完成"对零"
REFERENCE_TAGS = (1, 2, 3)

# 各编号目标的水平相对角度（度）：0° = ①②③ 方向，正方向朝 ④⑤⑥ 一侧
# 数值按 120×60 厘米场地地图几何推算（机器人位于场地中心），误差约 ±5 度，
# 跑几次后用 record_angle() 记录实测值替换
TARGET_ANGLES = {
    1: 0,      # 基准（①②③ 竖排杯架，上层）
    2: 0,      # 基准（中层）
    3: 0,      # 基准（下层）
    4: 28,     # 左上
    5: 52,     # 上中
    6: 132,    # 右上
    7: 163,    # 右侧双杯架（上层）
    8: 176,    # 右侧双杯架（下层）
    9: 211,    # 右下
    10: 343,   # 左下（约 -17°，按 0～360 记为 343）
}


def angle_of(tag_id):
    """查询目标相对 0° 的水平角度。

    输入：tag_id 标签编号
    输出：相对角度（度，0～360）；地图里没有的标签返回 None。
    """

    return TARGET_ANGLES.get(tag_id)


def shortest_turn(current, target):
    """计算两个相对角度之间的最短转向。

    输入：current 当前朝向（度）；target 目标朝向（度），均为相对角度
    输出：需要转过的角度（度）；正负号表示方向，范围 -180～180。
    """

    return (target - current + 180) % 360 - 180


def turn_angle(from_tag, to_tag):
    """查询"盯住 from_tag 时，要找 to_tag 该转多少度"。

    输入：from_tag 当前正对着的标签编号；to_tag 想要寻找的标签编号
    输出：需要转过的角度（度）；正负号表示方向，范围 -180～180，
         取的是最短转向。地图里没有的标签返回 None。
    """

    start = angle_of(from_tag)
    end = angle_of(to_tag)
    if start is None or end is None:
        return None
    return shortest_turn(start, end)


def record_angle(tag_id, angle):
    """把一次实测的相对角度记入地图，替换估算值。

    输入：tag_id 标签编号；angle 实测相对角度（度，任意大小，
         负角度或超过 360 会自动折算回 0～360）
    输出：无。
    """

    TARGET_ANGLES[tag_id] = angle % 360
